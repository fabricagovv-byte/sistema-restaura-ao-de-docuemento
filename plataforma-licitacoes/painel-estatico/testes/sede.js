const { chromium } = require('playwright');
(async () => { const b = await chromium.launch(); const erros = [];
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
  const p = await ctx.newPage(); p.on('pageerror', e => erros.push(e.message)); p.on('console', m => m.type() === 'error' && erros.push(m.text()));
  await p.goto('file://' + process.argv[2]);
  await p.waitForFunction(() => !document.getElementById('cat-todas').textContent.includes('carregando'), null, { timeout: 30000 });
  console.log('config:', await p.textContent('#cfg-estado'));
  await p.fill('#cfg-sede', 'Belo Horizonte/MG');
  await p.setInputFiles('#piso-arquivo', process.argv[3]); await p.waitForTimeout(300);
  console.log('upload:', await p.textContent('#cfg-estado'), '| linhas', await p.locator('#pisos-linhas tr').count());
  await p.click('#cfg-salvar'); await p.waitForTimeout(300);
  console.log('salvo:', await p.textContent('#cfg-estado'));
  await p.locator('#config-sec').screenshot({ path: 'config-cel.png' });
  await p.click('#cat-gv'); await p.waitForTimeout(150);
  const c1 = p.locator('.card').first();
  console.log('card dist:', await c1.locator('.dist').textContent().catch(() => '-'), '| pisos:', await c1.locator('.vol', { hasText: 'Pelos seus pisos' }).textContent().catch(() => '-'));
  await p.selectOption('#ord', 'dist'); await p.click('#cat-todas'); await p.waitForTimeout(150);
  console.log('mais perto:', (await p.locator('.card .dist').first().textContent()), (await p.locator('.card .topo b').first().textContent()));
  await p.fill('#dmax', '100'); await p.waitForTimeout(150); console.log('até 100 km:', (await p.textContent('#conta')).split('·')[0]);
  await p.fill('#dmax', ''); await p.click('#cat-remun_ust'); await p.waitForTimeout(150);
  await p.click('.card .abrir'); await p.waitForTimeout(300);
  console.log('mapa:', await p.locator('.mapa svg').count(), '|', (await p.textContent('.mapa p')).slice(0, 120));
  await p.locator('.mapa').screenshot({ path: 'mapa-cel.png' });
  await p.click('#abas [data-aba="preco"]'); await p.waitForTimeout(200);
  console.log('preço pelos pisos:', (await p.textContent('#pr-totais')).replace(/\s+/g, ' ').slice(0, 160));
  console.log('piso linha:', await p.locator('[data-piso]').first().textContent());
  await p.keyboard.press('Escape');
  await p.reload(); await p.waitForFunction(() => !document.getElementById('cat-todas').textContent.includes('carregando'), null, { timeout: 30000 });
  console.log('depois de recarregar:', await p.textContent('#cfg-estado'));
  console.log('largura', await p.evaluate(() => document.documentElement.scrollWidth), 'erros', erros); await b.close(); })();
